assert '"""#' not in html
keys = []
import re
for m in re.finditer(r"^    (\w+): \{ g: '(walk|world)', name: '([^']+)'", buddies, re.M):
    keys.append((m.group(1), m.group(2), m.group(3)))
swift = ('// Generated by tools/make_panel.py from the landing page. Edit there (or the runtime JS) and re-run.\n'
         'enum PanelHTML {\n'
         '    /// Every pop-up style: (key, "walk" or "world", display name).\n'
         '    static let styles: [(key: String, group: String, name: String)] = [\n' +
         ''.join('        ("%s", "%s", "%s"),\n' % k for k in keys) +
         '    ]\n\n'
         '    static func page(mode: String, buddy: String, locked: [String] = []) -> String {\n'
         '        let list = "[" + locked.map { "\\"" + $0 + "\\"" }.joined(separator: ",") + "]"\n'
         '        return template.replacingOccurrences(of: "__MODE__", with: mode).replacingOccurrences(of: "__BUDDY__", with: buddy)\n'
         '            .replacingOccurrences(of: "__LOCKED__", with: list)\n'
         '    }\n\n'
         '    static let template = #"""\n' + html + '\n"""#\n}\n')
pathlib.Path(sys.argv[2]).write_text(swift)
print('styles', len(keys), 'bytes', len(swift))
